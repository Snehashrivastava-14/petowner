const fs = require('fs');
const path = require('path');

// Read .env file
const envPath = path.join(__dirname, '.env');
const configPath = path.join(__dirname, 'config.js');

if (!fs.existsSync(envPath)) {
    console.error('.env file not found. Please create it with your API keys.');
    process.exit(1);
}

// Read and parse .env file
const envContent = fs.readFileSync(envPath, 'utf8');
const envVars = {};

envContent.split('\n').forEach(line => {
    const trimmedLine = line.trim();
    if (trimmedLine && !trimmedLine.startsWith('#')) {
        const [key, ...valueParts] = trimmedLine.split('=');
        if (key && valueParts.length > 0) {
            envVars[key.trim()] = valueParts.join('=').trim();
        }
    }
});

// Generate config.js content
const configContent = `// API Configuration
// This file is automatically generated from .env
// DO NOT edit this file directly - update .env instead

const API_KEYS = {
    // OpenAI API Key
    openai: '${envVars.OPENAI_API_KEY || 'YOUR_OPENAI_API_KEY'}',

    // NVIDIA build.nvidia API Key
    nvidia: '${envVars.NVIDIA_API_KEY || 'YOUR_NVIDIA_API_KEY'}',

    // OpenRouter API Key
    openrouter: '${envVars.OPENROUTER_API_KEY || 'YOUR_OPENROUTER_API_KEY'}'
};

// Supabase Configuration
const SUPABASE_URL = '${envVars.SUPABASE_URL || 'YOUR_SUPABASE_URL'}';
const SUPABASE_ANON_KEY = '${envVars.SUPABASE_ANON_KEY || 'YOUR_SUPABASE_ANON_KEY'}';
`;

// Write config.js
fs.writeFileSync(configPath, configContent);

console.log('✅ config.js generated successfully');
console.log('✅ API keys and Supabase configuration loaded from .env');
